export function findBestseller(title: string): Bestseller | null {
  const t = title.trim();
  if (!t) return null;
  return BESTSELLERS.find((b) => b.title === t || b.title.includes(t) || t.includes(b.title)) ?? null;
}

/** 제목으로 소개문을 찾는다(피어가 같은 책을 읽을 때 로컬 소개 보강용). */
export function blurbForTitle(title: string): string | null {
  return findBestseller(title)?.blurb ?? null;
}

export function tocForTitle(title: string): string[] {
  return [...(findBestseller(title)?.toc ?? [])];
}
